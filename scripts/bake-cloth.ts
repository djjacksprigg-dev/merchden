/**
 * Bakes cloth-simulated drapes for the clothing tops.
 *   npx vite-node scripts/bake-cloth.ts [kind ...]
 * Writes src/three/models/baked.ts. Re-run after changing garment shapes.
 */
import { writeFileSync, existsSync, readFileSync } from 'node:fs'
import { simulateTop } from '../src/three/models/drape'
import { simBody, sleeveTube, type TopKind } from '../src/three/models/garments'
import { encodeOffsets } from '../src/three/engine/drapeData'

const ALL: TopKind[] = ['tee', 'jersey', 'polo', 'sweatshirt', 'hoodie', 'zip-hoodie', 'jacket']
const only = process.argv.slice(2) as TopKind[]
const kinds = only.length ? only : ALL
const out = 'src/three/models/baked.ts'

let existing: Record<string, { body: string; sleeve: string }> = {}
if (existsSync(out)) {
  const m = readFileSync(out, 'utf8').match(/BAKED[^=]*= (\{[\s\S]*\})\s*$/)
  if (m) existing = JSON.parse(m[1])
}
for (const kind of kinds) {
  console.log(`Draping ${kind}…`)
  const loose = kind === 'hoodie' || kind === 'zip-hoodie' || kind === 'sweatshirt' || kind === 'jacket'
  const r = simulateTop(kind, console.log)
  const baseBody = Float32Array.from(simBody(kind).geometry.getAttribute('position').array as ArrayLike<number>)
  const baseSleeve = Float32Array.from(sleeveTube(loose, loose, true).geometry.getAttribute('position').array as ArrayLike<number>)
  existing[kind] = { body: encodeOffsets(r.body, baseBody), sleeve: encodeOffsets(r.sleeve, baseSleeve) }
  console.log(`  ${kind}: ${((existing[kind].body.length + existing[kind].sleeve.length) / 1024).toFixed(0)} KB`)
}
writeFileSync(
  out,
  `// Generated by scripts/bake-cloth.ts – cloth-simulated garment drapes (offsets from the base shapes).\n// Do not edit by hand.\nexport const BAKED: Record<string, { body: string; sleeve: string }> = ${JSON.stringify(existing, null, 0)}\n`,
)
console.log('Wrote', out)
